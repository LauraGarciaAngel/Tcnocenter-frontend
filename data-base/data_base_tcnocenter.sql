CREATE TABLE roles (
    id_rol BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(255),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
 
CREATE TABLE usuarios (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol BIGINT NOT NULL REFERENCES roles(id_rol) ON DELETE RESTRICT,
    nombre_completo VARCHAR(255) NOT NULL,
    correo_electronico VARCHAR(255) NOT NULL,
    contrasena_hash TEXT NOT NULL,
    telefono VARCHAR(25),
    estado BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT usuarios_correo_minusculas CHECK (
        correo_electronico = LOWER(correo_electronico)
    )
);
 
CREATE UNIQUE INDEX usuarios_correo_unico
    ON usuarios(LOWER(correo_electronico));
CREATE INDEX usuarios_id_rol_idx ON usuarios(id_rol);
 
CREATE TABLE marcas (
    id_marca BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    logo_url TEXT,
    estado BOOLEAN NOT NULL DEFAULT TRUE
);
 
CREATE TABLE categorias (
    id_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    estado BOOLEAN NOT NULL DEFAULT TRUE
);
 
CREATE TABLE colores (
    id_color BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL UNIQUE,
    codigo_hex CHAR(7),
    CONSTRAINT colores_hex_valido CHECK (
        codigo_hex IS NULL OR codigo_hex ~ '^#[0-9A-Fa-f]{6}$'
    )
);
 
CREATE TABLE etiquetas (
    id_etiqueta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL UNIQUE,
    color VARCHAR(30),
    etiqueta_url TEXT,
    estado BOOLEAN NOT NULL DEFAULT TRUE
);
 
CREATE TABLE productos (
    id_producto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_marca BIGINT NOT NULL REFERENCES marcas(id_marca) ON DELETE RESTRICT,
    id_etiqueta BIGINT REFERENCES etiquetas(id_etiqueta) ON DELETE SET NULL,
    id_categoria BIGINT NOT NULL REFERENCES categorias(id_categoria) ON DELETE RESTRICT,
    nombre VARCHAR(255) NOT NULL,
    modelo VARCHAR(160) NOT NULL,
    sku VARCHAR(100) UNIQUE,
    descripcion TEXT,
    camara NUMERIC(7, 2),
    os VARCHAR(80),
    stock_total BIGINT NOT NULL DEFAULT 0,
    estado BOOLEAN NOT NULL DEFAULT TRUE,
    producto_url TEXT,
    pantalla VARCHAR(100),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT productos_marca_modelo_unico UNIQUE (id_marca, modelo),
    CONSTRAINT productos_camara_no_negativa CHECK (camara IS NULL OR camara >= 0),
    CONSTRAINT productos_stock_no_negativo CHECK (stock_total >= 0)
);
 
CREATE INDEX productos_marca_idx ON productos(id_marca);
CREATE INDEX productos_categoria_idx ON productos(id_categoria);
CREATE INDEX productos_etiqueta_idx ON productos(id_etiqueta);
CREATE INDEX productos_estado_idx ON productos(estado);
 
CREATE TABLE producto_colores (
    id_producto_color BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_color BIGINT NOT NULL REFERENCES colores(id_color) ON DELETE RESTRICT,
    id_producto BIGINT NOT NULL REFERENCES productos(id_producto) ON DELETE CASCADE,
    almacenamiento INTEGER NOT NULL,
    precio NUMERIC(14, 2) NOT NULL,
    precio_anterior NUMERIC(14, 2),
    descuento NUMERIC(5, 2) GENERATED ALWAYS AS (
        CASE
            WHEN precio_anterior IS NULL OR precio_anterior <= 0 THEN 0
            ELSE ROUND((precio_anterior - precio) * 100.0 / precio_anterior, 2)
        END
    ) STORED,
    imagen_url TEXT,
    estado BOOLEAN NOT NULL DEFAULT TRUE,
    stock INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT producto_color_variante_unica UNIQUE (id_producto, id_color, almacenamiento),
    CONSTRAINT producto_color_almacenamiento_positivo CHECK (almacenamiento > 0),
    CONSTRAINT producto_color_precio_no_negativo CHECK (precio >= 0),
    CONSTRAINT producto_color_precio_anterior_valido CHECK (
        precio_anterior IS NULL OR precio_anterior > precio
    ),
    CONSTRAINT producto_color_stock_no_negativo CHECK (stock >= 0)
);
 
CREATE INDEX producto_colores_color_idx ON producto_colores(id_color);
CREATE INDEX producto_colores_producto_idx ON producto_colores(id_producto);
 
CREATE TABLE carritos (
    id_carrito BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT REFERENCES usuarios(id_usuario) ON DELETE CASCADE,
    token_invitado UUID UNIQUE,
    estado VARCHAR(20) NOT NULL DEFAULT 'activo',
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT carritos_estado_valido CHECK (
        estado IN ('activo', 'abandonado', 'convertido')
    ),
    CONSTRAINT carritos_propietario_requerido CHECK (
        (id_usuario IS NULL) <> (token_invitado IS NULL)
    )
);
 
CREATE UNIQUE INDEX carritos_un_activo_por_usuario
    ON carritos(id_usuario) WHERE id_usuario IS NOT NULL AND estado = 'activo';
 
CREATE TABLE items_carritos (
    id_item_carrito BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_carrito BIGINT NOT NULL REFERENCES carritos(id_carrito) ON DELETE CASCADE,
    producto_color_id BIGINT NOT NULL
        REFERENCES producto_colores(id_producto_color) ON DELETE RESTRICT,
    cantidad INTEGER NOT NULL,
    precio_unitario NUMERIC(14, 2) NOT NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT carrito_producto_color_unico UNIQUE (id_carrito, producto_color_id),
    CONSTRAINT items_carritos_cantidad_positiva CHECK (cantidad > 0),
    CONSTRAINT items_carritos_precio_no_negativo CHECK (precio_unitario >= 0)
);
 
CREATE INDEX items_carritos_carrito_idx ON items_carritos(id_carrito);
CREATE INDEX items_carritos_producto_color_idx ON items_carritos(producto_color_id);
 
CREATE TABLE resenas (
    id_resena BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES usuarios(id_usuario) ON DELETE RESTRICT,
    id_producto BIGINT NOT NULL REFERENCES productos(id_producto) ON DELETE RESTRICT,
    comentario TEXT,
    puntuacion NUMERIC(2, 1) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'pendiente',
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT resenas_usuario_producto_unicos UNIQUE (id_usuario, id_producto),
    CONSTRAINT resenas_puntuacion_valida CHECK (puntuacion >= 1 AND puntuacion <= 5),
    CONSTRAINT resenas_estado_valido CHECK (
        estado IN ('pendiente', 'publicada', 'rechazada')
    )
);
 
CREATE INDEX resenas_producto_estado_idx ON resenas(id_producto, estado);
 
-- Mantiene stock_total como suma del stock de las opciones de color del producto.
CREATE FUNCTION recalcular_stock_total(p_id_producto BIGINT)
RETURNS VOID
LANGUAGE plpgsql
AS $$
DECLARE
    v_stock_total BIGINT;
BEGIN
    PERFORM 1
      FROM productos
     WHERE id_producto = p_id_producto
     FOR UPDATE;
 
    IF NOT FOUND THEN
        RETURN;
    END IF;
 
    SELECT COALESCE(SUM(stock), 0)
      INTO v_stock_total
      FROM producto_colores
     WHERE id_producto = p_id_producto;
 
    UPDATE productos
       SET stock_total = v_stock_total,
           actualizado_en = NOW()
     WHERE id_producto = p_id_producto;
END;
$$;
 
CREATE FUNCTION sincronizar_stock_total_producto()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        PERFORM recalcular_stock_total(OLD.id_producto);
        RETURN OLD;
    ELSIF TG_OP = 'UPDATE' THEN
        IF OLD.id_producto <> NEW.id_producto THEN
            IF OLD.id_producto < NEW.id_producto THEN
                PERFORM recalcular_stock_total(OLD.id_producto);
                PERFORM recalcular_stock_total(NEW.id_producto);
            ELSE
                PERFORM recalcular_stock_total(NEW.id_producto);
                PERFORM recalcular_stock_total(OLD.id_producto);
            END IF;
        ELSE
            PERFORM recalcular_stock_total(NEW.id_producto);
        END IF;
        RETURN NEW;
    ELSE
        PERFORM recalcular_stock_total(NEW.id_producto);
        RETURN NEW;
    END IF;
END;
$$;
 
CREATE TRIGGER producto_colores_actualizar_stock_total
AFTER INSERT OR UPDATE OF id_producto, stock OR DELETE ON producto_colores
FOR EACH ROW
EXECUTE FUNCTION sincronizar_stock_total_producto();
 
COMMIT;